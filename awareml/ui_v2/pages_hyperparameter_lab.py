from __future__ import annotations

import pandas as pd
import streamlit as st

from .components import hero, empty_state, section
from .page_utils import phase_pills
from .state import ensure_research_state, result_dicts
from .framework_control import render_framework_configuration
from .hyperparameter_analysis import render_inline_hyperparameter_evidence


def hyperparameter_lab_page():
    hero(
        "CONFIGURATION EVIDENCE",
        "Hyperparameter Impact & Modification",
        (
            "Inspect how active algorithms and tunable parameters evolved during the observed stream, then prepare transparent next-run overrides. "
            "Observed association is kept separate from causal attribution."
        ),
        pills=phase_pills(),
    )
    state = ensure_research_state()
    results = result_dicts()

    section(
        "Observed hyperparameter evidence",
        "Window-level parameter history is generated by the backend during v6 runs. It is not reconstructed from final values after the fact.",
    )
    if results:
        frameworks = [str(r.get("framework")) for r in results]
        framework = st.selectbox("Framework evidence", frameworks, key="r120_hparam_evidence_fw")
        result = next(r for r in results if str(r.get("framework")) == framework)
        render_inline_hyperparameter_evidence(result, framework)
    else:
        empty_state(
            "No run evidence yet",
            "You can still prepare next-run configuration below. Run Studio will use the same saved configuration.",
        )

    section(
        "Modify the next run",
        "Configuration changes are prospective: they do not rewrite the current result or imply that a parameter is responsible for a past outcome.",
    )
    selected = st.multiselect(
        "Frameworks to configure",
        ["AutoStreamML", "AutoClass", "EvoAutoML", "OAML", "ChaCha"],
        default=["AutoStreamML", "AutoClass", "EvoAutoML", "OAML", "ChaCha"],
        key="r120_hparam_config_frameworks",
    )
    oaml_mode = st.selectbox(
        "OAML next-run mode",
        ["online", "gama"],
        index=0,
        key="r120_hparam_oaml_mode",
    )
    config = render_framework_configuration(
        selected,
        seed=42,
        key_prefix="r120_hparam_cfg",
        state=state,
        oaml_mode=oaml_mode,
        persist=False,
    )
    c1, c2 = st.columns([1, 1])
    with c1:
        if st.button("Save as next-run configuration", type="primary", use_container_width=True, key="r120_hparam_save"):
            state["framework_config_overrides"] = config
            state["preferred_oaml_mode"] = oaml_mode
            st.success("Saved. Run Studio will initialize its advanced framework controls from this configuration.")
    with c2:
        if st.button("Reset saved overrides", use_container_width=True, key="r120_hparam_reset"):
            state.pop("framework_config_overrides", None)
            state.pop("preferred_oaml_mode", None)
            st.success("Saved next-run overrides cleared.")

    with st.expander("Configuration payload preview", expanded=False):
        st.json(config, expanded=False)

    st.info(
        "For a causal hyperparameter claim, use a controlled sensitivity experiment that changes one parameter while holding the stream, seed, learner and remaining configuration fixed. The dashboard deliberately does not convert correlation into causation."
    )
